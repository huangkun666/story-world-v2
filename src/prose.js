// ★★★leg198：**「正文」这一层**——把"不是正文"的东西从文字里剥掉（结构判，不用标签名清单）。
//
// 它原来住在 `web/inject.js`（`proseOnly`），只服务**"找旧事的查询串"**那一处；
// 而**提取那一趟**（`src/tick.js` 的 `extractTags` 与落账那条链）拿的是**整条消息原文，一个字符都不剥**
// ⇒ 别的扩展的状态栏块（`<角色手机>…</角色手机>`，里面还套着一整套状态/动态/备忘）与
// 给自己看的 HTML 注释（`<!--抢话自查: …-->`）**一路进了提取**。
// 本笔把它搬进 `src/`（提取链在引擎这一层，而 `src/` **不许** import `web/`）并补两条能力。
//
// ＝＝ 口径（为什么是"成对块"这一条，而不是一张标签名清单）＝＝
//   ★本仓明禁"**用词表判语义**"（`ANCHOR.md` §4.8：换一本书/换一个扩展，词表就废）。
//   ⇒ 用**结构**判：**同名开标签与闭标签成对**的那一段，就是别的扩展的信封；正文不在里面。
//   实测核对过这条口径**不会吃掉正文**（真账最后一条）：正文包在**不成对的** `<content>` 开标签后面，
//   而剥掉的是 5 个成对块（`xzx_qyh` / `current_event` / `progress` / `konatan_chat` / `UpdateVariable`），
//   8225 字 → 3478 字，**尾部剩下的是干净的正文**。
//
// ＝＝ 三条边界（写死免得下一任改歪）＝＝
//   ① ★**不剥代码块**（三反引号那种）：模型写出来的 ```tags 块**本身就是最好的查询串**
//      （里面全是"谁做了什么"与账上真名）——剥了它等于把最有用的那几个字扔掉。
//      ★★而且从 leg198 起它还是**提取要读的料**：剥掉它 = 一整轮的标签全丢，那是最坏的失效形状。
//   ② ★**剥完是空的就退回原文**：万一某张卡把正文整个包在成对块里（换一个扩展就可能），
//      剥完就没有字了 ⇒ 那时退回原文 = **退化成今天的行为**，不会比今天更坏。
//   ③ ★★`keepTagsFence`（提取那一趟用的那一档）：**原文里有围栏、剥完没了 ⇒ 整段退回原文**。
//      理由：围栏本身不是 HTML 标签、不会被那个正则命中，但**它可能住在别人的信封里**
//      （`<角色手机>…```tags…```…</角色手机>`）⇒ 只按"成对块剥掉"办就会把标签一起剥没，而且一声不响。
//      ★"什么算一个围栏"**只有一处定义**（`src/tag-extract.js` 的 `shellRange`）——不在这里再写一遍。
//
// ＝＝ 一处定义、两处消费者（都只吃这一个函数）＝＝
//   · **找旧事的查询串**（`web/inject.js`）：默认那一档（行为与 leg136 起逐字节相同）；
//   · **提取那一趟**（`src/tick.js`）：`keepTagsFence: true`（多剥 HTML 注释 ＋ 围栏保命）。
//
// ＝＝ 实测曲线（查询串那一侧的，原文留在 `web/inject.js` 的调用点旁）＝＝
//   ★逐轮模拟 190 轮实测：**空手 67 轮（35.3%）**；把机器块剥掉之后 ⇒ **空手 25 轮（13.2%）**，
//     有货轮次平均从 1038 字涨到 2105 字。**一个改动，不动任何闸。**
import { shellRange } from './tag-extract.js';

/**
 * 剥掉机器块之后的正文。
 * @param {string} text 一条正文
 * @param {{keepTagsFence?: boolean}} [opts] `keepTagsFence` = 提取那一趟用（多剥 HTML 注释 ＋ 围栏保命）
 * @returns {string} 剥掉机器块之后的正文（剥空了 / 围栏被剥掉了 ⇒ **原样返回**）
 */
export function proseOnly(text, { keepTagsFence = false } = {}) {
    const s = String(text ?? '');
    if (!s) return '';
    // ★HTML 注释：`<!-- … -->`（只有"提取那一趟"剥它——查询串那一侧照旧不剥，免得动那条实测曲线）
    const base = keepTagsFence ? s.replace(/<!--[\s\S]*?-->/g, ' ') : s;
    // 同名开/闭成对（反向引用 `\1` 保证是同一个标签名；`[\s\S]*?` 非贪婪 ⇒ 不会跨块吃太多）
    // ★★★leg198：**名字那一格放宽了**——原来要求"名字以拉丁字母开头"（`[A-Za-z][\w:.-]*`），
    //   而社区反馈里那类块就叫 **`<角色手机>`**（中文名）⇒ 旧正则**一个都剥不掉**。
    //   新口径：名字 = "`<` 与 `>` 之间那段不含空白与斜杠的字"（结构判，仍然**不是**标签名清单）。
    const stripped = base.replace(/<([^\s/>]+)[^>]*>[\s\S]*?<\/\1\s*>/g, ' ');
    if (!stripped.trim()) return s;                       // 边界②：剥空 ⇒ 退回原文
    // 边界③：围栏被剥掉了 ⇒ 整段退回原文（宁可少剥，不许把标签剥没）
    if (keepTagsFence && shellRange(s) && !shellRange(stripped)) return s;
    return stripped;
}
